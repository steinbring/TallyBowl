#!/usr/bin/env python3
"""Render the bundled, offline app documents for repository/website reuse."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCUMENTS = {"privacy": "PRIVACY_POLICY", "guide": "USER_GUIDE"}


def render(name):
    data = json.loads((ROOT / f"assets/documents/{name}.json").read_text())
    lines = [f"# {data['title']}", "", f"Updated {data['updated']}.", ""]
    for section in data["sections"]:
        lines += [f"## {section['heading']}", ""]
        for paragraph in section["paragraphs"]:
            lines += [paragraph, ""]
    lines += ["## Links", ""]
    for link in data["links"]:
        lines += [f"- [{link['label']}]({link['url']})"]
    lines += ["", "<!-- Generated by tool/render_documents.py; edit assets/documents/*.json. -->", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated Markdown is stale")
    args = parser.parse_args()
    stale = []
    for name, filename in DOCUMENTS.items():
        path = ROOT / f"docs/{filename}.md"
        content = render(name)
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, "Stale documents: " + ", ".join(stale) + "\n")
    print("Bundled app documents and Markdown agree." if args.check else "Rendered app documents.")


if __name__ == "__main__":
    main()
